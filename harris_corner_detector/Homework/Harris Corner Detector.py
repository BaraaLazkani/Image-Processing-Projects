def conv(img,kernel):
    r = img.shape[0]
    c = img.shape[1]
    ker_r,ker_c = np.shape(kernel)
    ans = np.zeros((r,c))
    for i in range(ker_r//2,r-ker_r//2-1):
        for j in range(ker_c//2,c-ker_c//2-1):
            ans[i][j] = sum(sum((img[i-ker_r//2:i+ker_r//2+1,j-ker_c//2:j+ker_c//2+1])*kernel))
    return ans


